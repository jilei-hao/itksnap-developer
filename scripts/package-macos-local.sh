#!/usr/bin/env bash
# package-macos-local.sh — Make a DMG that runs on Apple silicon from a local
# ITK-SNAP build (Homebrew Qt, shared VTK, no signing certificate).
#
# Usage:
#   scripts/package-macos-local.sh <build-dir> [package-file-name]
#   scripts/package-macos-local.sh --fix-bundle <path/to/ITK-SNAP.app>
#
# The first form runs CPack and hooks the second form in through
# CPACK_PRE_BUILD_SCRIPTS, which runs after the bundle is staged and before
# the DMG is made, so the DMG keeps its license, background and layout.
#
# Why the bundle needs fixing (none of this happens in upstream CI, which
# links VTK statically and signs with a Developer ID certificate):
#   1. macdeployqt edits Homebrew's libraries, which breaks their ad-hoc
#      signatures. Apple silicon kills a process that loads a library with a
#      broken signature (exit 137), so everything is re-signed ad-hoc.
#   2. greedy and friends in Contents/bin link the shared VTK libraries but
#      have no rpath to Contents/Frameworks.
#   3. Some binaries keep absolute rpaths such as /opt/homebrew/lib, so on a
#      Mac with Homebrew they could load libraries from outside the bundle.
#
# The result is ad-hoc signed, not notarized: it runs on this Mac, and other
# Macs show a Gatekeeper warning (right-click > Open, or xattr -dr
# com.apple.quarantine ITK-SNAP.app). With Homebrew Qt it needs the macOS
# version of the build machine.
set -euo pipefail

usage() {
  sed -n '/^# Usage:/,/^# The first/{ /^# The first/d; s/^# \{0,1\}//; p }' "$0"
}

is_macho() { file -b "$1" | grep -q '^Mach-O'; }

adhoc_sign() {
  codesign --force --sign - "$1" 2>/dev/null ||
    { echo "ERROR: codesign failed for $1" >&2; codesign --force --sign - "$1"; exit 1; }
}

# All Mach-O files in the bundle except symlinks, deepest paths first
macho_files() {
  find "$1/Contents" -type f | awk '{ print length($0) "\t" $0 }' | sort -rn | cut -f2- |
    while IFS= read -r f; do is_macho "$f" && printf '%s\n' "$f"; done
}

fix_bundle() {
  local app="$1"
  [ -d "$app/Contents/MacOS" ] || { echo "ERROR: not an app bundle: $app" >&2; exit 1; }
  echo "==> Fixing $app"

  # codesign refuses files with extended attributes
  xattr -cr "$app"

  local f rp
  while IFS= read -r f; do
    # (3) drop absolute rpaths
    for rp in $(otool -l "$f" | awk '/cmd LC_RPATH/{ getline; getline; print $2 }' | grep '^/' || true); do
      install_name_tool -delete_rpath "$rp" "$f" 2>/dev/null
      echo "    removed rpath $rp from ${f#$app/}"
    done
    # (2) command-line tools need to find the bundled libraries
    case "$f" in
      "$app/Contents/bin/"*)
        if otool -L "$f" | grep -q '@rpath/' &&
           ! otool -l "$f" | grep -qE 'path @(loader|executable)_path/\.\./Frameworks'; then
          install_name_tool -add_rpath @executable_path/../Frameworks "$f" 2>/dev/null
          echo "    added rpath to ${f#$app/}"
        fi ;;
    esac
  done < <(macho_files "$app")

  # (1) re-sign inside-out: every binary, then each framework, then the app
  while IFS= read -r f; do
    [ "$f" = "$app/Contents/MacOS/ITK-SNAP" ] || adhoc_sign "$f"
  done < <(macho_files "$app")
  for f in "$app"/Contents/Frameworks/*.framework; do
    [ -d "$f" ] && adhoc_sign "$f"
  done
  adhoc_sign "$app"
  codesign --verify --deep --strict "$app"
  echo "==> Signature verified (ad-hoc)"
}

if [ "${1:-}" = "--fix-bundle" ]; then
  [ $# -eq 2 ] || { usage; exit 1; }
  fix_bundle "$2"
  exit 0
fi

case "${1:-}" in
  -h|--help) usage; exit 0 ;;
  "") usage; exit 1 ;;
esac

BUILD_DIR=$(cd "$1" && pwd)
[ -f "$BUILD_DIR/CPackConfig.cmake" ] || { echo "ERROR: no CPackConfig.cmake in $BUILD_DIR" >&2; exit 1; }
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

HOOK="$BUILD_DIR/package-macos-local.cmake"
cat > "$HOOK" <<EOF
# Generated by package-macos-local.sh; runs inside CPack.
file(GLOB _apps "\${CPACK_TEMPORARY_DIRECTORY}/*.app")
if(NOT _apps)
  message(FATAL_ERROR "No .app in \${CPACK_TEMPORARY_DIRECTORY}")
endif()
foreach(_app \${_apps})
  # The Bundle generator copies the icon in after this hook runs. Put the same
  # file there now, so that the signature already covers it.
  if(CPACK_BUNDLE_ICON)
    file(COPY_FILE "\${CPACK_BUNDLE_ICON}"
         "\${_app}/Contents/Resources/\${CPACK_BUNDLE_NAME}.icns")
  endif()
  execute_process(COMMAND "$SELF" --fix-bundle "\${_app}" RESULT_VARIABLE _rc)
  if(_rc)
    message(FATAL_ERROR "package-macos-local.sh --fix-bundle failed for \${_app}")
  endif()
endforeach()
EOF

CPACK_ARGS=(-G Bundle -D "CPACK_PRE_BUILD_SCRIPTS=$HOOK")
[ -n "${2:-}" ] && CPACK_ARGS+=(-D "CPACK_PACKAGE_FILE_NAME=$2")

echo "==> Packaging $BUILD_DIR"
(cd "$BUILD_DIR" && cpack "${CPACK_ARGS[@]}")
